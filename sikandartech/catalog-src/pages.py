def tail(r, scripts):
    files = ["icons.js", "catalog.js", "script.js", "shop-core.js", "product-info.js"] + scripts
    tags = "\n  ".join(f'<script src="{r}{f}"></script>' for f in files)
    return f"""
  <aside class="wa-aside" aria-label="WhatsApp chat"><a class="whatsapp-float" data-wa target="_blank" rel="noopener" aria-label="Chat on WhatsApp" data-ui-icon="brand-whatsapp"></a></aside>

  {tags}
</body>
</html>
"""


def page(r, head_html, body_cls, main, cat_by_id, scripts=(), active="", body_attrs=""):
    return (
        head_html
        + f'\n<body class="{body_cls}"{body_attrs}>\n  <a class="skip-link" href="#main">Skip to content</a>\n\n  '
        + header(r, active)
        + "\n\n"
        + main
        + "\n\n  "
        + footer(r, cat_by_id)
        + tail(r, list(scripts))
    )


def write(site, rel, text):
    path = os.path.join(site, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


# ---------------------------------------------------------------- pieces
def art(r, p, cat, eager=False):
    c = cat["color"]
    if p.get("photo"):
        load = 'fetchpriority="high"' if eager else 'loading="lazy"'
        return f'<div class="art photo" style="--c:{c}"><img src="{r}{p["photo"]}" alt="{e(p["name"])}" width="600" height="600" {load} decoding="async"></div>'
    return f'<div class="art" style="--c:{c}" role="img" aria-label="{e(p["name"])}"></div>'


def simple_card(r, p, cat):
    return f"""<article class="p-card" data-id="{p['id']}">
      <a href="{r}product/{p['id']}/" aria-label="{e(p['name'])}: product details">{art(r, p, cat)}</a>
      <div class="p-body">
        <div class="p-meta"><span class="p-cat">{e(cat['name'])}</span><span class="status {p['status']}">{STATUS_LABEL[p['status']]}</span></div>
        <h3><a href="{r}product/{p['id']}/">{e(p['name'])}</a></h3>
        <p class="p-desc">{e(p['desc'])}</p>
      </div>
    </article>"""


def cat_links(r, categories, products, active):
    def item(href, cid, name, count, color):
        cur = ' active" aria-current="page' if cid == active else ""
        return f'<a class="cat-btn{cur}" href="{href}" style="--c:{color}" data-cat="{cid}"><span class="ci" data-icon="{icon_of[cid]}"></span><span class="cn">{e(name)}</span><span class="cc">{count}</span></a>'

    icon_of = {"all": "layout-grid", **{c["id"]: c["icon"] for c in categories}}
    out = item(f"{r}shop/", "all", "All products", len(products), "#9aa0a8")
    out += "".join(item(f"{r}category/{c['id']}/", c["id"], c["name"], c["count"], c["color"]) for c in categories)
    return out


def crumbs_ld(items):
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": n, "item": SITE_URL + u} for i, (n, u) in enumerate(items)],
    }


def crumbs_html(r, items):
    parts = []
    for i, (n, u) in enumerate(items):
        if i == len(items) - 1:
            parts.append(f'<span aria-current="page">{e(n)}</span>')
        else:
            parts.append(f'<a href="{(r + u) if u else (r or "./")}">{e(n)}</a>')
    return '<span aria-hidden="true">/</span>'.join(parts)


