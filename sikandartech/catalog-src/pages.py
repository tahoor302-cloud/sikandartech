"""Static page generator for SikandarTech (called by build.py).

Writes crawlable pages with real URLs, unique metadata and structured data:
  shop/                      full catalogue
  category/<id>/             one page per category
  product/<id>/              one page per product
  privacy/, terms/, shipping-returns/
  404.html
and keeps the shared header and footer of index.html and ugc.html in sync.
The old query-string pages (products.html, product.html) become redirects.
"""
