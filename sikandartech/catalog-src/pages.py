def related_for(p, products):
    same = [x for x in products if x["cat"] == p["cat"] and x["id"] != p["id"]]
    i = products.index(p)
    after = [x for x in same if products.index(x) > i]
    before = [x for x in same if products.index(x) < i]
    return (after + before)[:4]


