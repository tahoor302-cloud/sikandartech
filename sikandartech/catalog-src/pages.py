# ---------------------------------------------------------------- shared header/footer in hand-written pages
def sync_partials(site, rel, cat_by_id, active):
    path = os.path.join(site, rel)
    text = open(path).read()
    text = re.sub(r"<!-- @header.*?<!-- /@header -->", lambda m: header("", active), text, flags=re.S)
    text = re.sub(r"<!-- @footer.*?<!-- /@footer -->", lambda m: footer("", cat_by_id), text, flags=re.S)
    open(path, "w").write(text)


# ---------------------------------------------------------------- entry point
def build(site, categories, products):
    cat_by_id = {c["id"]: c for c in categories}
    urls = ["", "shop/", "ugc.html"]

    # Shop
    h = head(
        "../", "Shop All Tech & Gadgets | SikandarTech",
        f"Browse {len(products)} advanced tech products in {len(categories)} categories: AI gadgets, computing, wearables, audio, cameras, drones, smart home and more. Request a factory quote.",
        "shop/",
        ld=[crumbs_ld([("Home", ""), ("Shop", "shop/")])],
    )
    write(site, "shop/index.html", page("../", h, "shop-page", shop_main("../", categories, products), cat_by_id, ["shop.js"], "shop", ' data-cat="all"'))

    # Categories
    for c in categories:
        r = "../../"
        items = [p for p in products if p["cat"] == c["id"]]
        path = f"category/{c['id']}/"
        desc = trim(f"{c['tagline']} Browse {c['count']} products in {c['name']}, sourced direct from manufacturers in China with inspection and worldwide shipping.")
        ld = [
            crumbs_ld([("Home", ""), ("Shop", "shop/"), (c["name"], path)]),
            {
                "@context": "https://schema.org", "@type": "CollectionPage", "name": c["name"], "description": c["tagline"], "url": SITE_URL + path,
                "mainEntity": {"@type": "ItemList", "numberOfItems": len(items), "itemListElement": [
                    {"@type": "ListItem", "position": i + 1, "url": f"{SITE_URL}product/{p['id']}/", "name": p["name"]} for i, p in enumerate(items)]},
            },
        ]
        h = head(r, f"{c['name']} | SikandarTech", desc, path, c.get("photo", DEFAULT_OG), ld=ld)
        grid = "".join(simple_card(r, p, c) for p in items)
        write(site, path + "index.html", page(r, h, "shop-page", shop_main(r, categories, products, c, grid), cat_by_id, ["shop.js"], "shop", f' data-cat="{c["id"]}"'))
        urls.append(path)

    # Products
    for p in products:
        r = "../../"
        c = cat_by_id[p["cat"]]
        path = f"product/{p['id']}/"
        desc = trim(f"{p['desc']} Key features: {', '.join(p['specs'][:3])}. Request a factory quote from SikandarTech.")
        prod_ld = {
            "@context": "https://schema.org", "@type": "Product", "name": p["name"], "description": p["desc"],
            "sku": code(products, p), "category": c["name"], "url": SITE_URL + path,
            "additionalProperty": [{"@type": "PropertyValue", "name": "Key feature", "value": s} for s in p["specs"]]
            + [{"@type": "PropertyValue", "name": "Availability", "value": STATUS_SCHEMA[p["status"]]}],
        }
        if p.get("photo"):
            prod_ld["image"] = SITE_URL + p["photo"]
        ld = [prod_ld, crumbs_ld([("Home", ""), ("Shop", "shop/"), (c["name"], f"category/{c['id']}/"), (p["name"], path)])]
        h = head(r, f"{p['name']} | SikandarTech", desc, path, p.get("photo") or c.get("photo") or DEFAULT_OG, ld=ld)
        main = product_main(r, p, c, products, related_for(p, products))
        write(site, path + "index.html", page(r, h, "shop-page pdp-page", main, cat_by_id, ["product.js"], "shop", f' data-product="{p["id"]}"'))
        urls.append(path)

    # Info pages
    for slug, d in INFO_PAGES.items():
        h = head("../", f"{d['title']} | SikandarTech", d["desc"], f"{slug}/", ld=[crumbs_ld([("Home", ""), (d["title"], f"{slug}/")])])
        write(site, f"{slug}/index.html", page("../", h, "info", info_main("../", slug, d), cat_by_id))
        urls.append(f"{slug}/")

    write(site, "404.html", not_found(cat_by_id))
    write(site, "products.html", REDIRECT_SHOP)
    write(site, "product.html", REDIRECT_PRODUCT)
    sync_partials(site, "index.html", cat_by_id, "")
    sync_partials(site, "ugc.html", cat_by_id, "community")

    with open(os.path.join(site, "sitemap.xml"), "w") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n')
        for u in urls:
            f.write(f"  <url><loc>{SITE_URL}{u}</loc></url>\n")
        f.write("</urlset>\n")
    return len(urls)
