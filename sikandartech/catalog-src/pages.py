def code(products, p):
    return "ST-" + str(products.index(p) + 1).zfill(4)


def trim(text, n=158):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= n else text[: n - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"


